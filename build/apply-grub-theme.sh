#!/usr/bin/env bash
# Stage the DeltaOS boot-menu theme into a live-build config tree.
#
#   apply-grub-theme.sh <build-work-dir>
#
# live-build copies config/bootloaders/grub-pc/* over its own template in the
# ISO's /boot/grub directory, and /boot/grub/config.cfg sources /boot/grub/
# theme.cfg while the menu is being built. Replacing theme.cfg is therefore the
# supported way to theme the menu without forking live-build's boot entries.
# The EFI build reuses the same grub.cfg, so one override covers BIOS and UEFI.
#
# Everything here is best-effort: if grub-mkfont or the DejaVu fonts are
# missing, no theme is installed and GRUB falls back to its stock look. Booting
# must never depend on theming.
set -euo pipefail

WORK="${1:?usage: apply-grub-theme.sh <build-work-dir>}"
THEME_DIR="$WORK/config/includes.binary/boot/grub/themes/deltaos"
BOOTLOADERS="$WORK/config/bootloaders"

log() { printf '\033[1;36m==> %s\033[0m\n' "$*"; }
skip() { log "$* -- keeping the stock GRUB menu"; exit 0; }

command -v grub-mkfont >/dev/null 2>&1 || skip "grub-mkfont not found"
[[ -f "$THEME_DIR/theme.txt" ]] || skip "theme.txt not generated"

# theme.txt asks for these families by name, so the .pf2 files must be built
# from matching faces or GRUB silently drops back to the default font.
render_font() { # <size> <ttf> <output>
    [[ -f "$2" ]] || return 1
    grub-mkfont -s "$1" -o "$3" "$2" 2>/dev/null || return 1
    [[ -s "$3" ]]
}

FONT_ROOT=/usr/share/fonts/truetype/dejavu
[[ -d "$FONT_ROOT" ]] || FONT_ROOT=/usr/share/fonts/truetype/liberation
[[ -d "$FONT_ROOT" ]] || skip "no DejaVu/Liberation fonts installed"

SANS="$FONT_ROOT/DejaVuSans.ttf"
BOLD="$FONT_ROOT/DejaVuSans-Bold.ttf"
MONO="$FONT_ROOT/DejaVuSansMono.ttf"
[[ -f "$SANS" ]] || SANS="$FONT_ROOT/LiberationSans-Regular.ttf"
[[ -f "$BOLD" ]] || BOLD="$SANS"
[[ -f "$MONO" ]] || MONO="$SANS"

log "rendering GRUB fonts"
render_font 24 "$BOLD" "$THEME_DIR/dejavu-sans-bold-24.pf2" || true
render_font 16 "$SANS" "$THEME_DIR/dejavu-sans-16.pf2" || true
render_font 16 "$MONO" "$THEME_DIR/dejavu-sans-mono-16.pf2" || true

# Remove fonts from earlier layouts so stale names cannot be loaded.
rm -f "$THEME_DIR/dejavu-sans-24.pf2" "$THEME_DIR/dejavu-sans-14.pf2"

if ! ls "$THEME_DIR"/*.pf2 >/dev/null 2>&1; then
    skip "font rendering produced no .pf2 files"
fi

# GRUB requires the fonts to be loaded *before* the theme is applied, and an
# unguarded loadfont on a missing file prints an error on every boot.
mkdir -p "$BOOTLOADERS/grub-pc"
cat > "$BOOTLOADERS/grub-pc/theme.cfg" <<'EOF'
# DeltaOS GRUB menu theme (generated by build/apply-grub-theme.sh).
# Keep a larger frame buffer than live-build's 800x600 default when the
# firmware offers one; GRUB falls through the list to auto.
set gfxmode=1280x720,1024x768,800x600,auto

insmod png

if [ -e ${prefix}/themes/deltaos/dejavu-sans-bold-24.pf2 ]; then
    loadfont ${prefix}/themes/deltaos/dejavu-sans-bold-24.pf2
fi
if [ -e ${prefix}/themes/deltaos/dejavu-sans-16.pf2 ]; then
    loadfont ${prefix}/themes/deltaos/dejavu-sans-16.pf2
fi
if [ -e ${prefix}/themes/deltaos/dejavu-sans-mono-16.pf2 ]; then
    loadfont ${prefix}/themes/deltaos/dejavu-sans-mono-16.pf2
fi

if [ -e ${prefix}/themes/deltaos/theme.txt ]; then
    set theme=${prefix}/themes/deltaos/theme.txt
else
    set color_normal=light-gray/black
    set color_highlight=white/dark-gray
fi
EOF

log "GRUB theme staged in $THEME_DIR"
